#!/usr/bin/env python3
"""Keep only RTL mutants that pass Jasper analyze + elaborate with the AQ setup.

This is a syntax/elaboration gate, not a proof that the mutant is reachable,
non-equivalent to golden RTL, or a representative real-world bug.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import re
import subprocess
import shlex
import tempfile
from process_watch import run_logged
from pathlib import Path

from collect_jasper import resolve, tcl_atom, tcl_list, input_fingerprint
from shared_results import Checker, environment, save_json, signature, sha


def syntax_tcl(config: dict, rtl_files: list[Path], assertion_file: Path,
               bind_files: list[Path], include_dirs: list[Path], defines: list[str],
               expected_assertions: int) -> str:
    for path in [*rtl_files, assertion_file, *bind_files, *include_dirs]:
        if not path.exists():
            raise ValueError(f"required source/include path missing: {path}")
    options = [f"+incdir+{x}" for x in include_dirs] + [f"+define+{x}" for x in defines]
    return f'''# Generated by validate_mutants.py: compile one RTL replacement.
set FH_TOP {tcl_atom(config["top"])}
set FH_RTL [list {tcl_list(rtl_files)}]
set FH_ASSERTION {tcl_atom(assertion_file)}
set FH_BIND [list {tcl_list(bind_files)}]
set FH_OPTIONS [list {tcl_list(options)}]
clear -all
if {{[catch {{
    analyze -sv {{*}}$FH_OPTIONS {{*}}$FH_RTL $FH_ASSERTION {{*}}$FH_BIND
    elaborate -top $FH_TOP
    set properties [get_property_list -include {{type assert}}]
    if {{[llength $properties] != {expected_assertions}}} {{
        error "active assertion count mismatch: [llength $properties] vs {expected_assertions}"
    }}
}} err]}} {{
    puts "FH_SYNTAX_FAIL $err"
    flush stdout
    exit -force
}}
puts "FH_SYNTAX_PASS"
flush stdout
exit -force
'''


def parse_validation_log(text: str, exit_code: int) -> tuple[str, str]:
    if exit_code == 0 and re.search(r"^FH_SYNTAX_PASS$", text, re.MULTILINE):
        return "PASS", "analyze and elaborate completed with expected AQ inventory"
    match = re.search(r"^FH_SYNTAX_FAIL\s*(.*)$", text, re.MULTILINE)
    return "FAIL", match.group(1).strip() if match else f"no pass token; exit={exit_code}"


def write_report(path: Path, rows: list[dict[str, str]]) -> None:
    handle = io.StringIO(newline="")
    writer = csv.DictWriter(handle, fieldnames=["id", "family", "operator", "site_id",
                                               "status", "reason", "log_file"])
    writer.writeheader()
    writer.writerows(rows)
    temporary = path.with_suffix('.csv.tmp')
    temporary.write_text(handle.getvalue(), encoding='utf-8')
    temporary.replace(path)


def completed_validation(text: str, returncode: int | None, timed_out: bool) -> bool:
    # License waits, timeouts and crashes are pending work, never evidence that
    # a mutant is invalid. Cache only an explicit completed Tcl decision.
    markers = re.findall(r'^FH_SYNTAX_(PASS|FAIL)(?:[ \t].*)?$', text, re.MULTILINE)
    return not timed_out and returncode == 0 and len(markers) == 1


def cached_validation(path: Path, identity: str) -> dict | None:
    try:
        cached = json.loads(path.read_text())
        if cached.get('schema') != 1 or cached.get('input_sha256') != identity:
            return None
        log_path = Path(cached['log_file'])
        data = log_path.read_bytes()
        if sha(data) != cached['log_sha256']:
            return None
        text = data.decode('utf-8', errors='replace')
        if not completed_validation(text, cached['returncode'], cached['timed_out']):
            return None
        status, reason = parse_validation_log(text, cached['returncode'])
        if cached.get('status') == status and cached.get('reason') == reason:
            return cached
    except (OSError, ValueError, KeyError, TypeError):
        pass
    return None


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True, help="candidate manifest")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--dry-run", action="store_true", help="write Tcl only; no PASS claims")
    args = parser.parse_args()
    validate(args.config, args.manifest, args.output, dry_run=args.dry_run)


def validate(config_path: Path, manifest_path: Path, output: Path, *, dry_run: bool = False) -> dict:
    config_path, manifest_path = config_path.resolve(), manifest_path.resolve()
    config = json.loads(config_path.read_text(encoding="utf-8"))
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if not isinstance(manifest.get("assertions"), list) or not manifest["assertions"]:
        raise ValueError("manifest.assertions must be a nonempty list")
    mutants = manifest.get("mutants")
    if not isinstance(mutants, list):
        raise ValueError("manifest.mutants must be a list")
    root = resolve(config.get("project_root", "."), config_path.parent)
    golden_rtl = [resolve(x, root) for x in config["rtl_files"]]
    assertion_file = resolve(config["assertion_file"], root)
    bind_files = [resolve(x, root) for x in config.get("bind_files", [])]
    include_dirs = [resolve(x, root) for x in config.get("include_dirs", [])]
    defines = config.get("defines", [])
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    checker = Checker(assertion_file.read_text(), manifest['assertions'], str(assertion_file))
    context = environment(config, root, checker, assertion_file)
    jobs: list[tuple[str, dict | None, list[Path]]] = []
    ids: set[str] = set()
    for item in mutants:
        if not isinstance(item, dict) or not all(isinstance(item.get(key), str) for key in ("id", "family", "replace", "file")):
            raise ValueError(f"invalid mutant manifest entry: {item}")
        mutant_id = item["id"]
        if not re.fullmatch(r"[A-Za-z0-9_.-]+", mutant_id) or mutant_id == "golden" or mutant_id in ids:
            raise ValueError(f"unsafe or duplicate mutant id: {mutant_id}")
        ids.add(mutant_id)
        replaced = resolve(item["replace"], root)
        mutant_file = resolve(item["file"], manifest_path.parent)
        if replaced not in golden_rtl or not mutant_file.is_file():
            raise ValueError(f"mutant {mutant_id}: replacement not in rtl_files or file missing")
        if item.get('sha256') and item['sha256'] != sha(mutant_file.read_bytes()):
            raise ValueError(f'mutant {mutant_id}: source hash disagrees with manifest')
        jobs.append((mutant_id, item, [mutant_file if x == replaced else x for x in golden_rtl]))

    passed: list[dict] = []
    report: list[dict[str, str]] = []
    # Preserve earlier reports; pre-checkpoint versions did not record input
    # hashes, so their raw PASS/FAIL rows cannot establish cache validity.
    previous_report = output / 'validation_report.csv'
    if not dry_run and previous_report.is_file():
        data = previous_report.read_bytes()
        archive = output / 'history' / ('validation_report_' + sha(data) + '.csv')
        if not archive.exists():
            archive.parent.mkdir(parents=True, exist_ok=True)
            archive.write_bytes(data)
    reused, measured = 0, 0
    for job_id, item, rtl_files in jobs:
        run_dir = output / "runs" / job_id
        run_dir.mkdir(parents=True, exist_ok=True)
        tcl = syntax_tcl(config, rtl_files, assertion_file, bind_files,
                         include_dirs, defines, len(manifest['assertions']))
        identity = signature({'protocol': 'syntax_checkpoint_v1', 'environment': context,
            'inputs': input_fingerprint(tcl, config, [*rtl_files, assertion_file, *bind_files], include_dirs)})
        if dry_run:
            tcl_file = run_dir / 'run.tcl'
            tcl_file.write_text(tcl, encoding='utf-8')
            print(f"DRY-RUN {job_id}: {tcl_file}")
            continue
        checkpoint = run_dir / 'validation_result.json'
        cached = cached_validation(checkpoint, identity)
        if cached is not None:
            status, reason, log_file = cached['status'], cached['reason'], Path(cached['log_file'])
            reused += 1
            print(f'REUSE SYNTAX {job_id}: {status}; no Jasper', flush=True)
        else:
            if (run_dir / 'run.log').is_file() and not checkpoint.exists():
                print(f'LEGACY SYNTAX {job_id}: no input fingerprint; retaining old log, checking once', flush=True)
            attempt = Path(tempfile.mkdtemp(prefix='attempt_', dir=run_dir))
            tcl_file, log_file = attempt / 'run.tcl', attempt / 'run.log'
            tcl_file.write_text(tcl, encoding='utf-8')
            print(f"SYNTAX {job_id}: {log_file}", flush=True)
            command = [config.get('jasper_executable', 'jg'), '-batch', str(tcl_file)]
            watched = run_logged(shlex.join(command), cwd=attempt, log_path=log_file,
                timeout_seconds=int(config.get('syntax_timeout_seconds', 1200)),
                label=f'syntax {job_id}', heartbeat_seconds=30)
            if not completed_validation(watched.output, watched.returncode, watched.timed_out):
                raise RuntimeError(f'Syntax job {job_id} did not complete (license wait/timeout/crash); '
                                   f'completed checkpoints preserved; retry this pending job; {log_file}')
            status, reason = parse_validation_log(watched.output, watched.returncode)
            save_json(checkpoint, {'schema': 1, 'input_sha256': identity, 'status': status,
                'reason': reason, 'log_file': str(log_file), 'log_sha256': sha(log_file.read_bytes()),
                'returncode': watched.returncode, 'timed_out': watched.timed_out})
            measured += 1
        report.append({"id": job_id, "family": item["family"] if item else "GOLDEN",
                       "operator": item.get("operator", "") if item else "",
                       "site_id": item.get("site_id", "") if item else "",
                       "status": status, "reason": reason, "log_file": str(log_file)})
        write_report(output / "validation_report.csv", report)
        if item is None and status != "PASS":
            raise RuntimeError(f"golden RTL/AQ setup does not elaborate: {reason}; see {log_file}")
        if item is not None and status == "PASS":
            accepted = dict(item)
            accepted["file"] = str(resolve(item["file"], manifest_path.parent))
            accepted["syntax_validated"] = True
            passed.append(accepted)
        print(f"{status} {job_id}: {reason}", flush=True)

    if not dry_run:
        filtered = {"assertions": manifest["assertions"], "mutants": passed}
        filtered_path = output / "validated_manifest.json"
        save_json(filtered_path, filtered)
        counts = {family: sum(item["family"] == family for item in passed)
                  for family in ("F1", "F2", "F3", "F4", "F5")}
        print(f"Wrote {filtered_path}; PASS mutants by family: {counts}")
    stats = {'reused': reused, 'measured': measured, 'candidates': len(jobs)}
    print(f'SYNTAX SUMMARY: reused={reused}, measured={measured}', flush=True)
    return stats


if __name__ == "__main__":
    main()
